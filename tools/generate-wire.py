"""Generate portable Swift wire constants from the canonical C headers."""
import argparse
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADERS = '\n'.join((ROOT / 'src' / name).read_text()
                    for name in ('control_proto.h', 'proto.h'))
DEFINES = dict(re.findall(r'^#define\s+((?:NDC|ND)_\w+)\s+([^\n/]+)', HEADERS, re.M))


def value(name):
    expression = re.sub(r'(?<=\d)[uUlL]+\b', '', DEFINES[name].strip())

    def integer(node):
        if isinstance(node, ast.Constant) and isinstance(node.value, int):
            return node.value
        if isinstance(node, ast.Name):
            return value(node.id)
        if isinstance(node, ast.BinOp):
            a, b = integer(node.left), integer(node.right)
            if isinstance(node.op, ast.LShift):
                return a << b
            if isinstance(node.op, ast.BitOr):
                return a | b
        raise ValueError(f'Unsupported wire constant: {name}')

    return integer(ast.parse(expression, mode='eval').body)


def generate():
    lines = ['// SPDX-License-Identifier: GPL-2.0-only',
             '// Generated by tools/generate-wire.py from src/{control_proto,proto}.h.',
             '// Edit the headers and regenerate; do not edit this file.']
    groups = {
        'NDProtocol': [
            ('controlMagic', 'NDC_MAGIC', 'UInt32'),
            ('version', 'NDC_VERSION', 'UInt16'),
            ('maxPayload', 'NDC_MAX_PAYLOAD', 'Int'),
            ('nonceSize', 'NDC_NONCE_SIZE', 'Int'),
            ('authSize', 'NDC_AUTH_SIZE', 'Int'),
            ('nameMax', 'NDC_NAME_MAX', 'Int'),
            ('udpPayloadMax', 'ND_UDP_PAYLOAD_MAX', 'Int'),
            ('videoQueueCapacity', 'ND_VIDEO_QUEUE_CAPACITY', 'Int'),
        ],
        'ControlFlags': [(swift, 'NDC_FLAG_' + c, 'UInt32') for swift, c in [
            ('wantInput', 'WANT_INPUT'), ('inputAllowed', 'INPUT_ALLOWED'),
            ('frameEncrypt', 'FRAME_ENCRYPT'), ('authRequired', 'AUTH_REQUIRED'),
            ('password', 'PASSWORD'), ('networkTest', 'NETWORK_TEST'),
            ('powerInfo', 'POWER_INFO'), ('touchscreen', 'TOUCHSCREEN'),
            ('predictedVideo', 'PREDICTED_VIDEO'),
        ]],
        'VideoCodecs': [(swift, 'NDC_CODEC_' + c, 'UInt32') for swift, c in [
            ('h264', 'H264'), ('hevc', 'HEVC'), ('av1', 'AV1'),
        ]],
    }
    for group, constants in groups.items():
        lines.append(f'enum {group} {{')
        for swift, c, kind in constants:
            lines.append(f'    static let {swift}: {kind} = {value(c)}')
        lines.append('}')
    for swift_enum, c_enum, prefix in [
        ('ControlType', 'ndc_type', 'NDC_'),
        ('VideoCodec', 'ndc_video_codec', 'NDC_VIDEO_'),
    ]:
        body = re.search(r'enum ' + c_enum + r'\s*\{(.*?)\};', HEADERS, re.S).group(1)
        body = re.sub(r'/\*.*?\*/|//[^\n]*', '', body, flags=re.S)
        lines.append(f'enum {swift_enum}: UInt16 {{')
        for entry in body.split(','):
            if not entry.strip():
                continue
            match = re.fullmatch(r'\s*' + prefix + r'(\w+)\s*=\s*(\d+)\s*', entry)
            if not match:
                raise ValueError(f'Unsupported wire enum entry: {entry}')
            c, number = match.groups()
            parts = c.lower().split('_')
            swift = parts[0] + ''.join(part.title() for part in parts[1:])
            lines.append(f'    case {swift} = {number}')
        lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'ios' / 'Core' / 'ProtocolConstants.swift'
    expected = generate()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            parser.exit(1, 'Swift protocol constants are stale; run python3 tools/generate-wire.py\n')
    else:
        output.write_text(expected)


if __name__ == '__main__':
    main()
